-- Snowpipe for stock prices
CREATE OR REPLACE PIPE STREAMING.STOCK_PRICES_PIPE
    AUTO_INGEST = TRUE
    AS
    COPY INTO STREAMING.FACT_STOCK_PRICES
    FROM @STREAMING.STREAMING_STAGE/fact_stock_prices/
    FILE_FORMAT = STREAMING.PARQUET_FORMAT
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    ON_ERROR = 'CONTINUE'
    PURGE = TRUE;

