-- =====================================================
-- 4. DIMENSION TABLES
-- =====================================================

-- DIM_COMPANY: Company information with SCD Type 2
CREATE OR REPLACE TABLE STREAMING.DIM_COMPANY (
    COMPANY_KEY NUMBER AUTOINCREMENT PRIMARY KEY,
    SYMBOL VARCHAR(10) NOT NULL,
    COMPANY_NAME VARCHAR(255),
    SECTOR VARCHAR(100),
    INDUSTRY VARCHAR(100),
    MARKET_CAP_CATEGORY VARCHAR(20),
    EXCHANGE VARCHAR(10),
    CURRENCY VARCHAR(3),
    COUNTRY VARCHAR(50),
    EFFECTIVE_DATE DATE NOT NULL,
    EXPIRY_DATE DATE,
    IS_CURRENT BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- DIM_DATE: Date dimension
CREATE OR REPLACE TABLE STREAMING.DIM_DATE (
    DATE_KEY NUMBER PRIMARY KEY,
    DATE_VALUE DATE NOT NULL,
    YEAR NUMBER,
    QUARTER NUMBER,
    MONTH NUMBER,
    MONTH_NAME VARCHAR(20),
    DAY_OF_MONTH NUMBER,
    DAY_OF_WEEK NUMBER,
    DAY_NAME VARCHAR(20),
    WEEK_OF_YEAR NUMBER,
    IS_WEEKEND BOOLEAN,
    IS_HOLIDAY BOOLEAN,
    IS_TRADING_DAY BOOLEAN,
    FISCAL_YEAR NUMBER,
    FISCAL_QUARTER NUMBER
);

-- DIM_TIME: Time dimension with market sessions
CREATE OR REPLACE TABLE STREAMING.DIM_TIME (
    TIME_KEY NUMBER PRIMARY KEY,
    TIME_VALUE TIME NOT NULL,
    HOUR NUMBER,
    MINUTE NUMBER,
    SECOND NUMBER,
    HOUR_MINUTE VARCHAR(5),
    AM_PM VARCHAR(2),
    MARKET_SESSION VARCHAR(20), -- 'PRE_MARKET', 'REGULAR', 'AFTER_HOURS', 'CLOSED'
    TRADING_DAY_MINUTE NUMBER -- Minutes since market open
);

-- =====================================================
-- 5. FACT TABLES
-- =====================================================

-- FACT_STOCK_PRICES: Main fact table for stock prices
CREATE OR REPLACE TABLE STREAMING.FACT_STOCK_PRICES (
    PRICE_KEY NUMBER AUTOINCREMENT PRIMARY KEY,
    COMPANY_KEY NUMBER NOT NULL,
    DATE_KEY NUMBER NOT NULL,
    TIME_KEY NUMBER NOT NULL,
    OPEN_PRICE DECIMAL(18,4),
    HIGH_PRICE DECIMAL(18,4),
    LOW_PRICE DECIMAL(18,4),
    CLOSE_PRICE DECIMAL(18,4),
    VOLUME NUMBER,
    ADJUSTED_CLOSE DECIMAL(18,4),
    DIVIDEND_AMOUNT DECIMAL(18,4),
    SPLIT_COEFFICIENT DECIMAL(10,6),
    
    -- Technical Indicators
    SMA_20 DECIMAL(18,4),
    SMA_50 DECIMAL(18,4),
    EMA_12 DECIMAL(18,4),
    EMA_26 DECIMAL(18,4),
    RSI_14 DECIMAL(8,4),
    MACD DECIMAL(18,4),
    MACD_SIGNAL DECIMAL(18,4),
    
    -- Metadata
    DATA_SOURCE VARCHAR(50),
    INGESTION_TIMESTAMP TIMESTAMP_NTZ,
    PROCESSING_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    
    FOREIGN KEY (COMPANY_KEY) REFERENCES STREAMING.DIM_COMPANY(COMPANY_KEY),
    FOREIGN KEY (DATE_KEY) REFERENCES STREAMING.DIM_DATE(DATE_KEY),
    FOREIGN KEY (TIME_KEY) REFERENCES STREAMING.DIM_TIME(TIME_KEY)
)
CLUSTER BY (COMPANY_KEY, DATE_KEY, TIME_KEY);

-- FACT_TRADING_VOLUME: Trading volume metrics
CREATE OR REPLACE TABLE STREAMING.FACT_TRADING_VOLUME (
    VOLUME_KEY NUMBER AUTOINCREMENT PRIMARY KEY,
    COMPANY_KEY NUMBER NOT NULL,
    DATE_KEY NUMBER NOT NULL,
    TIME_KEY NUMBER NOT NULL,
    VOLUME NUMBER NOT NULL,
    VOLUME_WEIGHTED_PRICE DECIMAL(18,4),
    TRADE_COUNT NUMBER,
    BUY_VOLUME NUMBER,
    SELL_VOLUME NUMBER,
    
    -- Volume Indicators
    VOLUME_SMA_20 NUMBER,
    VOLUME_RATIO DECIMAL(8,4), -- Current volume / Average volume
    
    -- Metadata
    DATA_SOURCE VARCHAR(50),
    INGESTION_TIMESTAMP TIMESTAMP_NTZ,
    PROCESSING_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    
    FOREIGN KEY (COMPANY_KEY) REFERENCES STREAMING.DIM_COMPANY(COMPANY_KEY),
    FOREIGN KEY (DATE_KEY) REFERENCES STREAMING.DIM_DATE(DATE_KEY),
    FOREIGN KEY (TIME_KEY) REFERENCES STREAMING.DIM_TIME(TIME_KEY)
)
CLUSTER BY (COMPANY_KEY, DATE_KEY, TIME_KEY);

