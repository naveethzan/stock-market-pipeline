-- Create a view for current stock prices with company information
CREATE OR REPLACE VIEW STREAMING.V_CURRENT_STOCK_PRICES AS
SELECT 
    c.SYMBOL,
    c.COMPANY_NAME,
    c.SECTOR,
    c.INDUSTRY,
    p.CLOSE_PRICE,
    p.VOLUME,
    p.SMA_20,
    p.SMA_50,
    p.RSI_14,
    d.DATE_VALUE,
    t.TIME_VALUE,
    t.MARKET_SESSION,
    p.PROCESSING_TIMESTAMP
FROM STREAMING.FACT_STOCK_PRICES p
JOIN STREAMING.DIM_COMPANY c ON p.COMPANY_KEY = c.COMPANY_KEY
JOIN STREAMING.DIM_DATE d ON p.DATE_KEY = d.DATE_KEY
JOIN STREAMING.DIM_TIME t ON p.TIME_KEY = t.TIME_KEY
WHERE c.IS_CURRENT = TRUE
  AND p.PROCESSING_TIMESTAMP >= DATEADD(DAY, -1, CURRENT_TIMESTAMP());

-- Create a view for daily trading summary
CREATE OR REPLACE VIEW STREAMING.V_DAILY_TRADING_SUMMARY AS
SELECT 
    c.SYMBOL,
    c.COMPANY_NAME,
    d.DATE_VALUE,
    MIN(p.LOW_PRICE) as DAY_LOW,
    MAX(p.HIGH_PRICE) as DAY_HIGH,
    FIRST_VALUE(p.OPEN_PRICE) OVER (PARTITION BY c.SYMBOL, d.DATE_VALUE ORDER BY t.TIME_VALUE) as DAY_OPEN,
    LAST_VALUE(p.CLOSE_PRICE) OVER (PARTITION BY c.SYMBOL, d.DATE_VALUE ORDER BY t.TIME_VALUE) as DAY_CLOSE,
    SUM(p.VOLUME) as TOTAL_VOLUME,
    COUNT(*) as PRICE_UPDATES
FROM STREAMING.FACT_STOCK_PRICES p
JOIN STREAMING.DIM_COMPANY c ON p.COMPANY_KEY = c.COMPANY_KEY
JOIN STREAMING.DIM_DATE d ON p.DATE_KEY = d.DATE_KEY
JOIN STREAMING.DIM_TIME t ON p.TIME_KEY = t.TIME_KEY
WHERE c.IS_CURRENT = TRUE
  AND d.IS_TRADING_DAY = TRUE
GROUP BY c.SYMBOL, c.COMPANY_NAME, d.DATE_VALUE;

